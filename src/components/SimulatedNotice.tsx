import { Info } from "lucide-react";
import { cn } from "../lib/utils";

/**
 * Required labeling: the execution/recovery layer is simulated.
 * This must be visible anywhere a run is shown.
 */
export function SimulatedNotice({ className, compact = false, reason }: { className?: string; compact?: boolean; reason?: string }) {
  return (
    <div
      className={cn(
        "flex items-start gap-2.5 rounded-lg border border-[#6b4a09] bg-[#2a1e04]/70 px-3 py-2.5 text-xs text-[#fbd38d]",
        className,
      )}
      role="note"
    >
      <Info aria-hidden="true" className="mt-0.5 h-4 w-4 shrink-0" />
      <p>
        <span className="font-semibold">Simulated recovery</span> — no containers, VMs or builds are executed.
        {!compact && " Logs, patches and verification levels are generated by a deterministic simulator."}
        {reason && ` ${reason}`}
      </p>
    </div>
  );
}
